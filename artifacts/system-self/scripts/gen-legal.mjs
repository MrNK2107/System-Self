// Bundles docs/legal/{privacy,terms,open-source-licences}.md into lib/legal/documents.generated.ts (no metro config needed, works in Expo Go).
// Run `pnpm run gen:legal` after editing a document; lib/legal/documents.test.ts fails if the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../../docs/legal/", import.meta.url);
const out = fileURLToPath(new URL("../lib/legal/documents.generated.ts", import.meta.url));
const read = (name) => readFileSync(new URL(`${name}.md`, root), "utf8").replace(/\r\n?/g, "\n");

// Key in the app (route /legal/<key>) -> file in docs/legal. open-source-licences.md is generated by gen-notices.mjs.
const docs = { privacy: "privacy", terms: "terms", licenses: "open-source-licences" };
const body = Object.entries(docs).map(([key, file]) => `  ${key}: ${JSON.stringify(read(file))},`).join("\n");
writeFileSync(
  out,
  `// GENERATED by scripts/gen-legal.mjs from docs/legal/*.md. Do not edit; run \`pnpm run gen:legal\`.\nexport const LEGAL_DOCS = {\n${body}\n} as const;\n`,
);
console.log(`wrote ${out}`);
