// Data the Status tab and the domain detail share: the profile line, the earned title and each domain's week change.
import { useQuery } from "@tanstack/react-query";
import type { Href } from "expo-router";
import { useMemo } from "react";

import { useApp, ACHIEVEMENT_DEFS, type Domain } from "@/context/AppContext";
import { useGameStateQuery, useGameUserId } from "@/hooks/useGameState";
import { usePro } from "@/hooks/usePro";
import { api } from "@/lib/api/client";
import { lifeContextOptions } from "@/lib/game/life";
import { FREE_CHART_DAYS, PRO_CHART_DAYS, fetchScoreHistory, scoreHistoryKey } from "@/lib/history/history";
import { latestTitle, weekChange } from "@/lib/status/status";

/** The score history query, keyed like the Stats chart so both read one cache entry. */
export function useScoreHistory() {
  const userId = useGameUserId();
  const days = usePro() ? PRO_CHART_DAYS : FREE_CHART_DAYS;
  return useQuery({ queryKey: scoreHistoryKey(userId, days), queryFn: () => fetchScoreHistory(api, days), enabled: !!userId });
}

export function useStatus() {
  const app = useApp();
  const stateQ = useGameStateQuery();
  const historyQ = useScoreHistory();

  const job = useMemo(() => {
    const key = stateQ.data?.profile.lifeContext;
    return key ? (lifeContextOptions().find((o) => o.key === key)?.label ?? null) : null;
  }, [stateQ.data]);

  const title = useMemo(
    () => latestTitle(app.milestones, app.achievements, (id) => ACHIEVEMENT_DEFS[id as keyof typeof ACHIEVEMENT_DEFS]?.title),
    [app.milestones, app.achievements],
  );

  const changes = useMemo(() => {
    const out = {} as Record<Domain, number | null>;
    for (const ds of app.domainScores) out[ds.domain] = weekChange(historyQ.data, ds.domain, ds.score);
    return out;
  }, [app.domainScores, historyQ.data]);

  return { ...app, job, title, changes, historyQ };
}

/** The domain detail route. Cast because the typed-route table is regenerated by the dev server, not by tsc. */
export const domainHref = (domain: string): Href => `/domain/${encodeURIComponent(domain)}` as Href;
