import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { test } from "node:test";
import { LEGAL_DOCS } from "./documents.generated";

const legalDir = resolve(__dirname, "../../../../docs/legal");
const read = (name: string) => readFileSync(resolve(legalDir, `${name}.md`), "utf8").replace(/\r\n?/g, "\n");

// The generated module is what ships. If this fails, run `pnpm run gen:legal` and commit the result.
test("the bundled legal text matches docs/legal/*.md exactly", () => {
  assert.equal(LEGAL_DOCS.privacy, read("privacy"));
  assert.equal(LEGAL_DOCS.terms, read("terms"));
  assert.equal(LEGAL_DOCS.licenses, read("open-source-licences"));
});

// The licence list is generated by `pnpm run gen:notices` from the lockfile. If these fail, re-run it and commit.
test("the open-source licence list covers every direct production dependency, and matches the full notices file", () => {
  const pkg = JSON.parse(readFileSync(resolve(__dirname, "../../package.json"), "utf8")) as { dependencies?: Record<string, string> };
  const listed = new Set([...LEGAL_DOCS.licenses.matchAll(/^- (\S+) (\S+): /gm)].map((m) => m[1]));
  assert.ok(listed.size > 50, `expected a real list, got ${listed.size} packages`);
  for (const name of Object.keys(pkg.dependencies ?? {})) {
    if (name.startsWith("@workspace/")) continue;
    assert.ok(listed.has(name), `${name} is missing from open-source-licences.md`);
  }
  const full = readFileSync(resolve(legalDir, "THIRD_PARTY_NOTICES-app.txt"), "utf8");
  const compact = [...LEGAL_DOCS.licenses.matchAll(/^- (\S+) (\S+): /gm)].map((m) => `${m[1]}@${m[2]}`);
  const inFull = [...full.matchAll(/^License: /gm)].length;
  assert.equal(inFull, compact.length, "both files list the same number of packages");
  for (const id of compact) assert.ok(full.includes(`
${id}
License: `), `${id} has a full entry in THIRD_PARTY_NOTICES-app.txt`);
});

test("both documents are marked DRAFT at the top and carry the placeholders the holds promise", () => {
  for (const doc of [LEGAL_DOCS.privacy, LEGAL_DOCS.terms]) assert.match(doc.split("\n")[0]!, /DRAFT/);
  assert.match(LEGAL_DOCS.privacy, /privacy@systemself\.app/);
  assert.match(LEGAL_DOCS.privacy, /Gemini/);
  assert.match(LEGAL_DOCS.privacy, /90 days/);
  assert.match(LEGAL_DOCS.privacy, /30 days/);
  assert.match(LEGAL_DOCS.privacy, /180 days/);
  assert.match(LEGAL_DOCS.privacy, /16/);
  assert.match(LEGAL_DOCS.privacy, /Resend/);
  assert.match(LEGAL_DOCS.privacy, /H-02/);
  assert.match(LEGAL_DOCS.privacy, /IP address/);
  assert.match(LEGAL_DOCS.terms, /16/);
  assert.match(LEGAL_DOCS.terms, /RevenueCat/);
});
